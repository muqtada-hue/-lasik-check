import streamlit as st

# إعدادات الصفحة
st.set_page_config(page_title="حاسبة أهلية الليزك وتصحيح البصر", page_icon="✨", layout="centered")

# تنسيق بصري أنيق
st.markdown("""
    <style>
    .main-header {
        text-align: center;
        color: #0F766E;
        font-size: 26px;
        font-weight: bold;
        margin-bottom: 5px;
    }
    .sub-header {
        text-align: center;
        color: #4B5563;
        font-size: 15px;
        margin-bottom: 25px;
    }
    </style>
""", unsafe_allow_html=True)

st.markdown('<p class="main-header">✨ هل تفكر بعملية ليزك أو تصحيح بصر؟</p>', unsafe_allow_html=True)
st.markdown('<p class="sub-header">أجب عن هذه الأسئلة السريعة لمعرفة مدى احتمالية ملاءمتك للعملية مبدئياً</p>', unsafe_allow_html=True)

st.write("---")

# نموذج الأسئلة التمهيدية للمرشح للعملية
with st.form("lasik_eligibility_form"):
    st.subheader("📋 استبيان أهليّة مبدئي:")
    
    # 1. العمر (العمر شرط أساسي لاستقرار النظر)
    age_group = st.selectbox(
        "1. ما هو عمرك الحالي؟",
        ["أقل من 18 سنة", "من 18 إلى 21 سنة", "من 22 إلى 40 سنة", "أكبر من 40 سنة"]
    )
    
    # 2. استقرار مقاس النظر
    stability = st.selectbox(
        "2. هل مقاس نظارتك أو عدساتك ثابت خلال السنة الأخيرة أم يتغير باستمرار؟",
        ["ثابت تماماً لأكثر من سنة", "لا أعرف / يتغير أحياناً", "يتغير باستمرار كل بضعة أشهر"]
    )
    
    # 3. نوع المشكلة البصرية السائدة
    vision_issue = st.selectbox(
        "3. ما هي المشكلة البصرية التي تعاني منها غالباً؟",
        ["قصر نظر (لا أرى البعيد بوضوح)", "طول نظر (أصعب في القراءة القريبة)", "استجماتيزم (غباش أو تشوش في الرؤية)", "مجموعة مما سبق"]
    )
    
    # 4. الحالة الصحية أو العينية الخاصة
    special_conditions = st.multiselect(
        "4. هل توجد أي من الحالات التالية تنطبق عليك؟ (اختر إن وجدت)",
        [
            "أعاني من جفاف شديد ومزمن في العين",
            "أنا حامل أو أرضع حالياً (للنساء)",
            "لدي أمراض مناعية أو مزمنة (مثل السكري غير المستقر)",
            "لا شيء مما ذكر"
        ]
    )
    
    submitted = st.form_submit_button("احصل على تقييم أهليتك المبدئي 🔍")

# تحليل النتائج وإعطاء التوجيه الطبي التسويقي
if submitted:
    st.write("---")
    st.subheader("📊 نتيجة التقييم المبدئي:")
    
    # منطق التقييم التميزي
    if age_group == "أقل من 18 سنة":
        st.warning("⏳ **العمر قد يكون عائقاً مؤقتاً حالياً.**")
        st.write("عمليات تصحيح البصر تتطلب عادةً استقرار النمو البصري ويفضل أن يكون عمر المراجع 18 عاماً فما فوق. ننصحك بالانتظار واستشارة أخصائي المركز للاطمئنان.")
    elif stability == "يتغير باستمرار كل بضعة أشهر":
        st.warning("⚠️ **استقرار النظر شرط أساسي.**")
        st.write("بما أن مقاس نظرك غير ثابت، فمن المرجح أن يطلب منك الطبيب الانتظار حتى يستقر النظر تماماً قبل إجراء أي عملية. ندعوك لفحص دوري لتتبع الحالة.")
    elif any("جفاف شديد" in cond or "حامل" in cond or "أمراض مناعية" in cond for cond in special_conditions):
        st.info("💡 **تتطلب تقييماً خاصاً ودقيقاً لدى الطبيب.**")
        st.write("وجود بعض الحالات مثل الجفاف الشديد أو الحمل يتطلب فحصاً سريرياً دقيقاً (مثل قياس سماكة القرنية وفحص سطح العين) لتحديد ما إذا كانت تقنيات مثل الـ PRK أو الفيمتو ليزك تناسبك أم لا.")
    else:
        st.success("🎉 **مؤشراتك الأولية تبدو واعدة جداً للعملية!**")
        st.write("بناءً على إجاباتك، تبدو مرشحاً محتملاً ممتازاً لعمليات تصحيح البصر. الخطوة الحاسمة الآن هي إجراء **فحص قرنية شامل ومفصل (Corneal Topography & Tomography)** في مركزنا للتأكد من سماكة القرنية وصلاحيتها بشكل قطعي.")

    # زر حجز موعد خصيصاً للعمليات
    st.write("---")
    st.info("🎯 **الخطوة التالية:** احجز موعداً لـ 'فحص تقييم الليزك الشامل' في مركزنا لتحديد التقنية الأنسب لعينيك (ليزك، فيمتو ليزك، أو زراعة عدسات).")
